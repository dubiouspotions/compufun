    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for name, rows in ICONS.items():
        write_png(os.path.join(out, name + ".png"), grid(rows))
    write_png(os.path.join(out, "logo_32.png"), grid(LOGO_32))
